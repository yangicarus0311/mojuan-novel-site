def continuation(title: str, chapter_number: int, chapter_title: str) -> str:
    story = STORIES[title]
    step = (chapter_number - 1) % 10
    arc = (chapter_number - 1) // 10
    incident = chapter_title.split(" ", 1)[-1] if title == "深海囚笼" and chapter_number > 10 else PLOT_STEPS[title][step]
    previous = PLOT_STEPS[title][step - 1] if step else "上一段旅程留下的疑问"
    lines = [f"{chapter_title}\n\n" + f"{story.setting}里，{incident}。{story.hero}想起{previous}，知道这两件事必然有关。{story.partner}带着{story.token}赶来，他们决定从{story.places[(step + arc) % len(story.places)]}查起。眼前的{chapter_title.split(' ', 1)[-1]}并非故事的终点，而是{story.secret}第一次露出清晰轮廓。"]
    for index, beat in enumerate(BEATS):
        number = chapter_number + index
        values = dict(
            hero=story.hero, partner=story.partner, opponent=story.opponent,
            setting=story.setting, goal=story.goal, secret=story.secret, token=story.token,
            place=story.places[number % len(story.places)],
            clue=story.clues[(number // 2) % len(story.clues)],
            pressure=story.pressures[(number // 3) % len(story.pressures)],
            incident=incident, previous=previous,
        )
        lines.append(beat.format(**values) + HOOKS[index][0].format(**values))
        lines.append(DETAILS[index].format(**values) + HOOKS[index][1].format(**values))
        if index == 7:
            lines.append(f"关于“{incident}”的第一轮查证到这里有了结果：{story.hero}找到了证据，也发现{story.opponent}提前知道他们的路线。{story.partner}建议换一条路继续，不要再按别人准备好的顺序打开下一道门。")
        elif index == 15:
            lines.append(f"第二轮查证把{previous}与{incident}连在了一起。{story.hero}与{story.partner}交换各自记下的时间，终于看清{story.opponent}刻意漏掉的一段经过。两人决定带着这段空白当面对质。")
        elif index == 23:
            lines.append(f"等到所有证据摊开，{story.hero}承认“{incident}”只是更大问题的一部分。他和{story.partner}约定先保护证人，再沿着{story.secret}留下的痕迹继续查下去。")
    lines.append(f"天快亮时，{story.hero}与{story.partner}约好下一次见面的地点。{story.token}仍在他的掌心，{story.goal}也还远未完成。这一夜关于“{incident}”的证据足以让他们迈出下一步；至于{story.opponent}会怎样回应，只能等下一次天光。")
    return "\n\n".join(lines)


def demo_title(title: str, number: int) -> str:
    return f"第{number}章 {PLOT_STEPS[title][(number - 1) % 10]}"


def expanded_content(title: str, number: int, chapter_title: str, current: str) -> str:
    if title not in STORIES:
        return current
    written = continuation(title, number, chapter_title)
    if is_seed_stub(current):
        return written
    return (current or "").rstrip() + "\n\n" + written

