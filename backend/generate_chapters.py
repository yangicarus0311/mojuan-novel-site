def generate_chapter_content(chapter_num, title):
    title_line = "第{}章 {}".format(chapter_num, title)

    p1 = P1[(chapter_num * 2) % len(P1)]
    p2 = P2[(chapter_num * 3 + 1) % len(P2)]
    p3 = P3[(chapter_num * 5 + 2) % len(P3)]
    p4 = P4[(chapter_num * 7 + 3) % len(P4)]

    content = "{}\n\n{}\n\n{}\n\n{}\n\n{}".format(title_line, p1, p2, p3, p4)

    stripped = content.replace('\n', '').replace(' ', '').replace('\u3000', '')
    word_count = len(stripped)

    return content, word_count


def generate_chapters():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    cursor.execute("SELECT MAX(chapter_number) FROM chapters WHERE work_id = ?", (7,))
    start_chapter = (cursor.fetchone()[0] or 0) + 1
    end_chapter = 100

    cursor.execute("SELECT word_count FROM works WHERE id = ?", (7,))
    current_word_count = cursor.fetchone()[0]

    total_new_words = 0
    chapters_added = 0

    print("Generating chapters {} to {} for work_id=7 (深海囚笼)...".format(start_chapter, end_chapter))

    for cn in range(start_chapter, end_chapter + 1):
        title = CHAPTER_TITLES[(cn - 1) % len(CHAPTER_TITLES)]
        content, wc = generate_chapter_content(cn, title)
        total_new_words += wc

        cursor.execute(
            "INSERT INTO chapters (work_id, chapter_number, volume_id, title, content, word_count, created_at) "
            "VALUES (?, ?, 1, ?, ?, ?, ?)",
            (7, cn, "第{}章 {}".format(cn, title), content, wc,
             datetime.now() - timedelta(hours=(100 - cn)))
        )
        chapters_added += 1
        if chapters_added % 15 == 0:
            print("  Added {} chapters... (sample wc={})".format(chapters_added, wc))

    new_wc = current_word_count + total_new_words
    cursor.execute("UPDATE works SET word_count = ?, updated_at = ? WHERE id = ?",
                   (new_wc, datetime.now(), 7))

    conn.commit()
    conn.close()

    print("\nDone! Added {} chapters.".format(chapters_added))
    print("Previous: {} | New: {} | Total: {}".format(current_word_count, total_new_words, new_wc))


if __name__ == "__main__":
    generate_chapters()
